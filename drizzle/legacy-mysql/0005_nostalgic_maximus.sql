CREATE TABLE `appointments` (
	`id` int AUTO_INCREMENT NOT NULL,
	`tracking_id` varchar(20) NOT NULL,
	`customer_name` varchar(255) NOT NULL,
	`customer_email` varchar(320) NOT NULL,
	`customer_phone` varchar(50) NOT NULL,
	`consultation_type` varchar(100) NOT NULL DEFAULT 'health_advice',
	`request_details` text NOT NULL,
	`appointment_date` timestamp NOT NULL,
	`duration` int NOT NULL DEFAULT 30,
	`base_price` varchar(20) NOT NULL,
	`final_price` varchar(20) NOT NULL,
	`is_night_rate` int NOT NULL DEFAULT 0,
	`stripe_payment_intent_id` varchar(255),
	`stripe_session_id` varchar(255),
	`payment_status` enum('pending','completed','failed','refunded') NOT NULL DEFAULT 'pending',
	`appointment_status` enum('confirmed','cancelled','completed','no_show') NOT NULL DEFAULT 'confirmed',
	`meet_link` varchar(500),
	`cancellation_reason` text,
	`cancelled_at` timestamp,
	`refund_amount` varchar(20),
	`refunded_at` timestamp,
	`email_sent` int NOT NULL DEFAULT 0,
	`sms_sent` int NOT NULL DEFAULT 0,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `appointments_id` PRIMARY KEY(`id`),
	CONSTRAINT `appointments_tracking_id_unique` UNIQUE(`tracking_id`)
);
