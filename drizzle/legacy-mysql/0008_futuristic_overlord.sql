CREATE TABLE `cv_applications` (
	`id` int AUTO_INCREMENT NOT NULL,
	`tracking_id` varchar(20) NOT NULL,
	`first_name` varchar(120) NOT NULL,
	`last_name` varchar(120) NOT NULL,
	`email` varchar(320) NOT NULL,
	`phone` varchar(50),
	`specialty` varchar(160) NOT NULL,
	`target_countries` text NOT NULL,
	`languages` text,
	`years_experience` int,
	`message` text,
	`cv_file_key` varchar(500) NOT NULL,
	`cv_original_name` varchar(255) NOT NULL,
	`cv_mime_type` varchar(100) NOT NULL,
	`cv_size_bytes` int NOT NULL,
	`gdpr_consent` int NOT NULL DEFAULT 0,
	`marketing_consent` int NOT NULL DEFAULT 0,
	`status` enum('new','reviewing','shortlisted','placed','rejected','archived') NOT NULL DEFAULT 'new',
	`admin_notes` text,
	`consent_at` timestamp,
	`retention_until` timestamp,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `cv_applications_id` PRIMARY KEY(`id`),
	CONSTRAINT `cv_applications_tracking_id_unique` UNIQUE(`tracking_id`)
);
